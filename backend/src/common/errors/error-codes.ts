import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/** One `code` thrown somewhere in `src/`. */
export interface ErrorCodeEntry {
  code: string;
  /** Feature area: the module folder (or `common`, `tenancy`, `shared`). */
  area: string;
  /** The first message thrown with it. */
  message: string;
}

/** `code: 'X'` in an error body, or a domain error built with its code first. */
const CODE = /(?:code:\s*|new \w+Error\(\s*)'([A-Z][A-Z0-9_]+)'/g;
/** Sort directions on a column named `code`, not error codes. */
const NOT_CODES = new Set(['ASC', 'DESC']);
const MESSAGE = /message:\s*(?:'([^']*)'|"([^"]*)"|`([^`]*)`)/;

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (name.endsWith('.ts') && !name.endsWith('.spec.ts')) out.push(path);
  }
  return out;
}

const areaOf = (root: string, file: string) => {
  const parts = relative(root, file).split(sep);
  return parts[0] === 'modules' ? parts[1] : parts[0];
};

/**
 * Every API error `code` in the source (`code: 'SOME_CODE'` next to a
 * message), sorted by area and code. The frontend maps these to Bangla and
 * English text; `doc/error-codes.md` is generated from this.
 */
export function collectErrorCodes(srcRoot: string): ErrorCodeEntry[] {
  const found = new Map<string, ErrorCodeEntry>();
  for (const file of walk(srcRoot)) {
    if (file.includes(`${sep}migrations${sep}`)) continue;
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(CODE)) {
      const code = match[1];
      if (found.has(code) || NOT_CODES.has(code)) continue;
      // The message is usually just above the code in the same object.
      const before = text.slice(Math.max(0, match.index - 400), match.index);
      const messages = [...before.matchAll(new RegExp(MESSAGE, 'g'))];
      // Domain errors pass the message right after the code.
      const after = text
        .slice(match.index, match.index + 300)
        .match(/'[A-Z][A-Z0-9_]+',\s*(?:'([^']*)'|`([^`]*)`)/);
      const last = after
        ? [after[0], after[1], undefined, after[2]]
        : messages[messages.length - 1];
      found.set(code, {
        code,
        area: areaOf(srcRoot, file),
        message: (last?.[1] ?? last?.[2] ?? last?.[3] ?? '')
          .replace(/\s+/g, ' ')
          .trim(),
      });
    }
  }
  return [...found.values()].sort(
    (a, b) => a.area.localeCompare(b.area) || a.code.localeCompare(b.code),
  );
}

/** The Markdown reference (`npm run docs:error-codes`). */
export function renderErrorCodes(entries: ErrorCodeEntry[]): string {
  const lines = [
    '# API error codes',
    '',
    'Generated by `npm run docs:error-codes` from the `code` values thrown in `backend/src`; do not edit by hand.',
    '',
    'Every error response is `{ success: false, statusCode, message, code?, … }`. The frontend shows its own Bangla or English text for `code` and falls back to `message` (English). Some errors carry more fields (for example `enrollmentIds`, `problems`).',
    '',
  ];
  let area = '';
  for (const e of entries) {
    if (e.area !== area) {
      area = e.area;
      lines.push(
        `## ${area}`,
        '',
        '| Code | Message (English) |',
        '| ---- | ----------------- |',
      );
    }
    lines.push(`| \`${e.code}\` | ${e.message.replace(/\|/g, '\\|') || '—'} |`);
    const next = entries[entries.indexOf(e) + 1];
    if (!next || next.area !== area) lines.push('');
  }
  return lines.join('\n');
}
